"""Render the README's results and registry sections from out/report.json.

The README text between the BEGIN/END markers is generated, so every published
number is exactly what `make reproduce` computes (tests/test_published.py checks it).
"""

from __future__ import annotations

import json

RESULTS = ("<!-- RESULTS:BEGIN (generated by `python -m vaultcheck readme`) -->", "<!-- RESULTS:END -->")
REGISTRY = ("<!-- REGISTRY:BEGIN (generated by `python -m vaultcheck readme`) -->", "<!-- REGISTRY:END -->")
SUMMARY_KO = ("<!-- SUMMARY_KO:BEGIN (generated by `python -m vaultcheck readme`) -->", "<!-- SUMMARY_KO:END -->")


def _usd(x) -> str:
    return "-" if x is None else f"${x:,.0f}"


def _doubling_run(levels: list[float]) -> tuple[int, int] | None:
    """Longest index range where each consecutive ratio is ~2 or ~4."""
    best, start = None, 0
    for i in range(1, len(levels) + 1):
        ok = i < len(levels) and any(abs(levels[i] / levels[i - 1] - k) <= 0.05 * k for k in (2, 4))
        if not ok:
            if i - 1 - start >= 3 and (best is None or i - 1 - start > best[1] - best[0]):
                best = (start, i - 1)
            start = i
    return best


def render_results(r: dict) -> str:
    inc = r["incident"]
    out = ["## Results: the October incident, replayed from public chain state", ""]
    out.append(f"Incident token: `{inc['token']}` (USDT on BNB Chain via HOT Omni, {inc['decimals']} decimals). "
               f"{inc['points']} archival snapshots between blocks {inc['first_block']:,} and {inc['last_block']:,}; "
               "threshold crossings located to the exact block by bisection.")
    out.append("")
    out.append("| Alarm threshold (unbacked USDT) | First block | Time (UTC) | Unbacked then | Before the team identified it (1 Oct 08:04) |")
    out.append("| --- | ---: | --- | ---: | ---: |")
    for c in inc["crossings"]:
        name = "first unbacked unit" if c["threshold_usd"] == 0 else _usd(c["threshold_usd"])
        if not c["block"]:
            out.append(f"| {name} | never | | | |")
        else:
            out.append(f"| {name} | {c['block']:,} | {c['time_utc']} | {_usd(c['gap_usd'])} | {c['hours_before_identified']:.1f} h |")
    p, a = inc["peak"], inc["at_identification"]
    out.append("")
    out.append(f"- Peak: {_usd(p['gap_usd'])} unbacked at block {p['block']:,} ({p['time_utc']} UTC): the ledger owed {p['ledger']:,.0f} USDT while the vault held {p['vault']:,.0f}.")
    out.append(f"- At the moment the team identified the problem, {_usd(a['gap_usd'])} was unbacked (block {a['block']:,}, {a['time_utc']} UTC).")
    pl = inc.get("plateaus_usd") or []
    if len(pl) >= 4:
        steps = " → ".join(f"{v:,.0f}" for v in pl)
        run = _doubling_run(pl)
        tail = ""
        if run:
            lo, hi = run
            tail = (f" From {pl[lo]:,.0f} to {pl[hi]:,.0f} every step is ×2 or ×4 (a ×4 step hides an intermediate level "
                    "that the snapshots caught at most once).")
        out.append(f"- On the way up the unbacked amount (USDT) sat at these levels: {steps}.{tail} "
                   "Brief dips inside a block are deposits that reached the vault before the ledger update and refund executed.")
    if inc["closure"]:
        c = inc["closure"]
        out.append(f"- The gap closed at block {c['block']:,} ({c['time_utc']} UTC), when the returned funds were back in the vault; the last unbacked amount was {_usd(c['last_unbacked_gap_usd'])}.")
    for f in r["pause_flips"]:
        out.append(f"- `pa_is_paused(ALL)` turned {'true' if f['to'] == 'paused' else 'false'} at block {f['block']:,} ({f['time_utc']} UTC); the post-mortem says {f['postmortem_time_utc']}.")
    scans = r["scans"]
    if scans:
        out.append("")
        out.append(f"### Every fungible token, {scans[0]['time_utc'][:10]} to {scans[-1]['time_utc'][:10]}")
        out.append("")
        win = [s for s in scans if s["time_utc"] < "2026-10-04"]
        alarmed = sorted({a["token"] for s in win for a in s["alarms"]})
        out.append(f"{len(scans)} full scans of {scans[0]['tokens']} fungible token ids ({len(win)} inside 27 Sep - 3 Oct). "
                   f"Baseline = the first scan; ALARM = an unbacked gap grew by at least $1,000 (or 1% of the ledger when no price is known).")
        out.append("")
        out.append(f"- Token ids that raised an ALARM in the incident window: {', '.join(f'`{t}`' for t in alarmed) or 'none'}.")
        if r.get("naive_baseline_alarms") is not None:
            out.append(f"- A naive `ledger <= vault` rule with no baseline would have been red for {r['naive_baseline_alarms']} token ids on 27 Sep, two days before the attack (see the registry below).")
        out.append("")
        out.append("| Block | Time (UTC) | Backed | Standing | Drift | Unverifiable | ALARM |")
        out.append("| ---: | --- | ---: | ---: | ---: | ---: | --- |")
        for s in scans:
            c = s["counts"]
            al = ", ".join(f"{a['symbol'] or a['token'][:20]} {_usd(a['growth_usd'])}" for a in s["alarms"]) or "none"
            out.append(f"| {s['block']:,} | {s['time_utc'][:16]} | {c['backed']} | {c['standing']} | {c['drift']} | {c['unverifiable']} | {al} |")
    return "\n".join(out)


def render_registry(r: dict, registry: dict) -> str:
    out = []
    classes = registry["classes"]
    tokens = registry["tokens"]
    counts: dict[str, int] = {}
    for t in tokens.values():
        counts[t["class"]] = counts.get(t["class"], 0) + 1
    out.append(f"`data/registry.json` classifies by hand {len(tokens)} token ids whose ledger > vault gap has nothing to do with the October incident. "
               "They are shown as `standing` or `drift`, never hidden.")
    out.append("")
    out.append("| Class | Ids | Why |")
    out.append("| --- | ---: | --- |")
    for k, desc in classes.items():
        out.append(f"| `{k}` | {counts.get(k, 0)} | {desc} |")
    return "\n".join(out)


def render_summary_ko(r: dict) -> str:
    """Korean key results for README.ko.md, from the same report.json as the English tables."""
    inc = r["incident"]
    cross = {c["threshold_usd"]: c for c in inc["crossings"]}
    c0, c1k, p, a = cross[0], cross[1000], inc["peak"], inc["at_identification"]
    out = [
        f"- **첫 미담보 발생:** 블록 {c0['block']:,} ({c0['time_utc']} UTC). 장부가 금고보다 {_usd(c0['gap_usd'])} 더 많아진 순간입니다.",
        f"- **$1,000 경보:** 블록 {c1k['block']:,} ({c1k['time_utc']} UTC). 팀이 문제를 파악한 10월 1일 08:04 UTC보다 **{c1k['hours_before_identified']:.1f}시간** 앞섭니다.",
        f"- **최대 미담보액:** {_usd(p['gap_usd'])} (블록 {p['block']:,}, {p['time_utc']} UTC). 장부는 {p['ledger']:,.0f} USDT를 빚졌고 금고에는 {p['vault']:,.0f} USDT만 있었습니다.",
        f"- **팀이 파악한 시점의 미담보액:** {_usd(a['gap_usd'])} (블록 {a['block']:,}, {a['time_utc']} UTC).",
    ]
    if inc["closure"]:
        c = inc["closure"]
        out.append(f"- **차이 해소:** 블록 {c['block']:,} ({c['time_utc']} UTC). 회수된 자금이 금고로 돌아와 장부를 다시 담보했습니다.")
    for f in r["pause_flips"]:
        word = "true(일시정지)" if f["to"] == "paused" else "false(재개)"
        out.append(f"- **`pa_is_paused(ALL)` {word}:** 블록 {f['block']:,} ({f['time_utc']} UTC). 사후 보고서 기록은 {f['postmortem_time_utc']}입니다.")
    scans = r["scans"]
    if scans:
        win = [s for s in scans if s["time_utc"] < "2026-10-04"]
        alarmed = sorted({x["token"] for s in win for x in s["alarms"]})
        who = "사고 토큰 하나뿐" if alarmed == [inc["token"]] else ", ".join(f"`{x}`" for x in alarmed) or "없음"
        out.append(f"- **전체 토큰 점검:** {scans[0]['tokens']}개 대체 가능 토큰을 {len(scans)}번 전수 점검했고, 사고 기간에 경보를 낸 토큰은 {who}입니다.")
        if r.get("naive_baseline_alarms") is not None:
            out.append(f"- **단순 비교 규칙이라면:** 기준선 없이 `ledger <= vault`만 보면 공격 이틀 전인 9월 27일에 이미 {r['naive_baseline_alarms']}개 토큰 id에 빨간불이 켜졌을 것입니다.")
    return "\n".join(out)


def _replace(text: str, markers: tuple[str, str], body: str) -> str:
    begin, end = markers
    i, j = text.index(begin), text.index(end)
    return text[: i + len(begin)] + "\n" + body + "\n" + text[j:]


def update(readme: str = "README.md", report: str = "out/report.json", registry: str = "data/registry.json",
           readme_ko: str = "README.ko.md") -> None:
    with open(report) as f:
        r = json.load(f)
    with open(registry) as f:
        reg = json.load(f)
    with open(readme) as f:
        text = f.read()
    text = _replace(text, RESULTS, render_results(r))
    text = _replace(text, REGISTRY, render_registry(r, reg))
    with open(readme, "w") as f:
        f.write(text)
    try:
        with open(readme_ko) as f:
            ko = f.read()
    except FileNotFoundError:
        return
    ko = _replace(ko, SUMMARY_KO, render_summary_ko(r))
    ko = _replace(ko, RESULTS, render_results(r))
    ko = _replace(ko, REGISTRY, render_registry(r, reg))
    with open(readme_ko, "w") as f:
        f.write(ko)


def section(text: str, markers: tuple[str, str]) -> str:
    begin, end = markers
    return text[text.index(begin) + len(begin) : text.index(end)].strip("\n")
